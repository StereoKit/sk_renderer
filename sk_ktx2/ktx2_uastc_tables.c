// Callers reach this only for a pattern that ktx2_uastc_pattern accepted, so
// the index is already known good.
uint32_t ktx2_uastc_astc_seed(uint32_t mode, uint32_t subsets, uint32_t pattern) {
	if (mode    == 7) return k_seed72[pattern];
	if (subsets == 3) return k_seed3 [pattern];
	return                   k_seed2 [pattern];
}
