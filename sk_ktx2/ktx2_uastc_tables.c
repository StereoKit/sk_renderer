const uint8_t* ktx2_uastc_dequant(uint32_t range) {
	switch (range) {
	case 7:  return k_dequant7;
	case 12: return k_dequant12;
	case 13: return k_dequant13;
	case 18: return k_dequant18;
	case 19: return k_dequant19;
	default: return NULL; // a pure-bit range, bit-replicated instead
	}
}

