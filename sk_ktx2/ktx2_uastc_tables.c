// NULL is a single-subset mode, or a pattern index with nothing behind it -
// one of the ways a UASTC block can be invalid.
const uint8_t* ktx2_uastc_pattern(uint32_t mode, uint32_t subsets, uint32_t pattern) {
	if (subsets  < 2) return NULL;
	if (mode    == 7) return pattern < 19 ? k_pattern72[pattern] : NULL;
	if (subsets == 3) return pattern < 11 ? k_pattern3 [pattern] : NULL;
	return                   pattern < 30 ? k_pattern2 [pattern] : NULL;
}

